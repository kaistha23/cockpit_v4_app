def _q19(release_id: str) -> dict[str, Any]:
    period = periods(release_id)
    now = _sector_totals(period["latest"], release_id)
    then = _sector_totals(period["prior"], release_id)

    def book(frame):
        ead, ecl = float(frame["ead"].sum()), float(frame["ecl"].sum())
        stage2 = float(frame["stage2_ead"].sum())
        return {"ead": ead, "ecl": ecl, "coverage": ecl / ead,
                "stage2_share": stage2 / ead}

    current, prior = book(now), book(then)
    top_sector = now.sort_values(["ecl", "sector_name"],
                                 ascending=[False, True]).iloc[0]
    borrowers = _borrower_totals(period["latest"], release_id).sort_values(
        ["ecl", "borrower_id"], ascending=[False, True]).iloc[0]
    return {
        "period": period["latest"], "comparison": period["prior"],
        "kpis": current, "kpis_prior": prior,
        "changes": {k: current[k] - prior[k] for k in current},
        "top_sector": {"sector_name": top_sector.sector_name,
                       "ecl": float(top_sector.ecl)},
        "top_borrower": {"borrower_id": borrowers.borrower_id,
                         "ecl": float(borrowers.ecl)},
        "row_count": 1}


def _q20(release_id: str) -> dict[str, Any]:
    """Deterioration on at least two of four measures. The rule is published."""
    period = periods(release_id)
    now = _sector_totals(period["latest"], release_id).set_index("sector_name")
    then = _sector_totals(period["prior"], release_id).set_index("sector_name")
    facility = _facility(release_id)

    def weighted_rank(quarter):
        slice_ = facility[facility["reporting_quarter"] == quarter]
        ratings = _rating_at(quarter, release_id).set_index("borrower_id")
        merged = slice_.join(ratings, on="borrower_id")
        rated = merged[merged["rating_rank"].notna()]
        if rated.empty:
            return pd.Series(dtype=float)
        weight = rated.groupby("sector_name", observed=True).apply(
            lambda d: float((d["ead_reported"] * d["rating_rank"]).sum()
                            / d["ead_reported"].sum()),
            include_groups=False)
        return weight

    def past_due_share(quarter):
        slice_ = facility[facility["reporting_quarter"] == quarter]
        total = slice_.groupby("sector_name", observed=True)[
            "ead_reported"].sum()
        overdue = slice_[slice_["days_past_due"].fillna(0) > 0].groupby(
            "sector_name", observed=True)["ead_reported"].sum()
        return overdue.reindex(total.index).fillna(0.0) / total

    rank_now, rank_then = weighted_rank(period["latest"]), weighted_rank(
        period["prior"])
    dpd_now, dpd_then = past_due_share(period["latest"]), past_due_share(
        period["prior"])

    rows = []
    for sector in sorted(set(now.index) & set(then.index)):
        measures = {
            "ecl": float(now["ecl"][sector] - then["ecl"][sector]),
            "stage2_share": float(now["stage2_share"][sector]
                                  - then["stage2_share"][sector]),
            "rating_rank": (float(rank_now[sector] - rank_then[sector])
                            if sector in rank_now and sector in rank_then
                            else None),
            "past_due_share": float(dpd_now[sector] - dpd_then[sector]),
        }
        worse = sorted(k for k, v in measures.items()
                       if v is not None and v > 0)
        missing = sorted(k for k, v in measures.items() if v is None)
        if len(worse) >= 2:
            rows.append({"sector_name": sector, "deteriorated_on": worse,
                         "count": len(worse), "measures": measures,
                         "missing_measures": missing})
    rows.sort(key=lambda r: (-r["count"], r["sector_name"]))
    return {"period": period["latest"], "comparison": period["prior"],
            "rows": rows, "row_count": len(rows),
            "rule": ("a measure counts as deteriorated when it moved in the "
                     "adverse direction between the two quarters; a sector "
                     "qualifies on two or more, and a measure with no value "
                     "is reported as missing rather than counted")}


