"""
The overnight analytical benchmark: twenty senior-credit-risk questions.

Three evidence layers, kept apart on purpose.

LAYER A — the ORACLE. `oracle()` computes the expected answer with pandas,
straight from the published Parquet. It imports nothing from the query path,
the catalog, the validator or the executor. It is allowed to disagree, and
while this file was being written it did — twice.

LAYER B — the INDEPENDENT ANALYST. `sql_for()` is SQL authored against the
catalogue by a reader of the question, not generated by the product. In the
harness it stands in for what Opus would write. If it disagrees with Layer A,
one of the two is wrong and the test says so rather than averaging them.

LAYER C — the PRODUCT. The test module drives the real V4: intake, context,
tool contracts, validator, bind proof, DuckDB, artifacts, finalizer, events.

Nothing here is hard-coded. Every expected number is calculated from the
pinned release at test time, so the bank travels to a different release and
still means something.
"""

from __future__ import annotations

import os
from typing import Any

import pandas as pd

RELEASE = os.environ.get("COCKPIT_V4_TEST_RELEASE", "v4-saudi-20q-v1")


def _frame(relation: str, release_id: str = "") -> pd.DataFrame:
    os.environ.setdefault("COCKPIT_AGENTIC_V3_NAMESPACE", "cockpit_v4")
    from backend.cockpit_agentic import store

    return pd.read_parquet(
        store.relation_path(release_id or RELEASE, relation))


def quarters(release_id: str = "") -> list[str]:
    frame = _frame("cockpit_facility_quarter", release_id)
    return sorted(str(q) for q in frame["reporting_quarter"].dropna().unique())


def periods(release_id: str = "") -> dict[str, str]:
    slots = quarters(release_id)
    return {"latest": slots[-1], "prior": slots[-2], "year_ago": slots[-5],
            "last_four": slots[-4:]}


def _facility(release_id: str = "") -> pd.DataFrame:
    frame = _frame("cockpit_facility_quarter", release_id)
    return frame[frame["sector_name"].notna()]


def _borrower_ratings(release_id: str = "") -> pd.DataFrame:
    return _frame("cockpit_rating_ratio_quarter", release_id)[
        ["reporting_quarter", "borrower_id", "risk_rating", "rating_rank"]]


