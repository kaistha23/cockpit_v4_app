# ---- LAYER A: the oracle ------------------------------------------------

def _sector_totals(quarter: str, release_id: str = "") -> pd.DataFrame:
    slice_ = _facility(release_id)
    slice_ = slice_[slice_["reporting_quarter"] == quarter]
    grouped = slice_.groupby("sector_name", observed=True).agg(
        ead=("ead_reported", "sum"), ecl=("ecl_reported", "sum"),
        facilities=("facility_id", "count"))
    stage2 = slice_[slice_["ifrs9_stage"] == 2].groupby(
        "sector_name", observed=True)["ead_reported"].sum()
    grouped["stage2_ead"] = stage2.reindex(grouped.index).fillna(0.0)
    grouped["stage2_share"] = grouped["stage2_ead"] / grouped["ead"]
    grouped["coverage"] = grouped["ecl"] / grouped["ead"]
    return grouped.reset_index()


def _borrower_totals(quarter: str, release_id: str = "") -> pd.DataFrame:
    slice_ = _facility(release_id)
    slice_ = slice_[slice_["reporting_quarter"] == quarter]
    grouped = slice_.groupby(["borrower_id", "borrower_name", "sector_name"],
                             observed=True).agg(
        ead=("ead_reported", "sum"), ecl=("ecl_reported", "sum"),
        worst_stage=("ifrs9_stage", "max"),
        max_dpd=("days_past_due", "max")).reset_index()
    return grouped


def _rating_at(quarter: str, release_id: str = "") -> pd.DataFrame:
    ratings = _borrower_ratings(release_id)
    return ratings[ratings["reporting_quarter"] == quarter][
        ["borrower_id", "risk_rating", "rating_rank"]]


def _q01(release_id: str) -> dict[str, Any]:
    period = periods(release_id)["latest"]
    totals = _sector_totals(period, release_id).sort_values(
        ["ead", "sector_name"], ascending=[False, True])
    rows = [{"sector_name": r.sector_name, "ead": float(r.ead)}
            for r in totals.itertuples()]
    total = sum(r["ead"] for r in rows)
    return {"period": period, "rows": rows, "total_ead": total,
            "top_sector": rows[0]["sector_name"],
            "top_share": rows[0]["ead"] / total, "row_count": len(rows)}


def _q02(release_id: str) -> dict[str, Any]:
    period = periods(release_id)["latest"]
    borrowers = _borrower_totals(period, release_id).sort_values(
        ["ecl", "borrower_id"], ascending=[False, True]).head(10)
    rows = [{"borrower_id": r.borrower_id, "borrower_name": r.borrower_name,
             "sector_name": r.sector_name, "stage": int(r.worst_stage),
             "ead": float(r.ead), "ecl": float(r.ecl)}
            for r in borrowers.itertuples()]
    book = _sector_totals(period, release_id)["ecl"].sum()
    return {"period": period, "rows": rows, "row_count": len(rows),
            "book_ecl": float(book),
            "top10_share": sum(r["ecl"] for r in rows) / float(book)}


def _q03(release_id: str) -> dict[str, Any]:
    period = periods(release_id)["latest"]
    totals = _sector_totals(period, release_id)
    stage2_total = float(totals["stage2_ead"].sum())
    rows = [{"sector_name": r.sector_name, "stage2_ead": float(r.stage2_ead),
             "share": float(r.stage2_ead) / stage2_total if stage2_total else
             None}
            for r in totals.itertuples() if float(r.stage2_ead) > 0]
    rows.sort(key=lambda row: (-row["stage2_ead"], row["sector_name"]))
    return {"period": period, "rows": rows, "row_count": len(rows),
            "total_stage2_ead": stage2_total,
            "shares_sum": sum(r["share"] for r in rows) if rows else 0.0}


def _q04(release_id: str) -> dict[str, Any]:
    window = periods(release_id)["last_four"]
    covenant = _frame("cockpit_covenant_quarter", release_id)
    slice_ = covenant[covenant["reporting_quarter"].isin(window)]
    breached = slice_[slice_["breach_date"].notna()]
    grouped = breached.groupby(["borrower_id", "reporting_quarter"],
                               observed=True).agg(
        breaches=("covenant_id", "nunique"),
        waived=("waiver_flag", "max")).reset_index()
    rows = [{"borrower_id": r.borrower_id, "quarter": r.reporting_quarter,
             "breaches": int(r.breaches), "waiver": bool(r.waived)}
            for r in grouped.sort_values(
                ["borrower_id", "reporting_quarter"]).itertuples()]
    return {"periods": window, "rows": rows, "row_count": len(rows),
            "borrowers": sorted({r["borrower_id"] for r in rows}),
            "unwaived": sorted({r["borrower_id"] for r in rows
                                if not r["waiver"]})}


def _downgrades(new_q: str, old_q: str, release_id: str) -> pd.DataFrame:
    """A downgrade is a rating_rank that got WORSE. A higher rank is weaker."""
    now, then = _rating_at(new_q, release_id), _rating_at(old_q, release_id)
    joined = now.merge(then, on="borrower_id", suffixes=("_now", "_then"))
    return joined[joined["rating_rank_now"] > joined["rating_rank_then"]]


def _q05(release_id: str) -> dict[str, Any]:
    period = periods(release_id)
    moved = _downgrades(period["latest"], period["prior"], release_id)
    totals = _borrower_totals(period["latest"], release_id).set_index(
        "borrower_id")
    rows = []
    for row in moved.itertuples():
        if row.borrower_id not in totals.index:
            continue
        entry = totals.loc[row.borrower_id]
        rows.append({"borrower_id": row.borrower_id,
                     "previous_rating": row.risk_rating_then,
                     "current_rating": row.risk_rating_now,
                     "notches": int(row.rating_rank_now - row.rating_rank_then),
                     "ead": float(entry["ead"]), "ecl": float(entry["ecl"])})
    rows.sort(key=lambda r: (-r["notches"], -r["ead"], r["borrower_id"]))
    return {"period": period["latest"], "comparison": period["prior"],
            "rows": rows, "row_count": len(rows),
            "ead_downgraded": sum(r["ead"] for r in rows),
            "ecl_downgraded": sum(r["ecl"] for r in rows)}


def _q06(release_id: str) -> dict[str, Any]:
    period = periods(release_id)
    now = _sector_totals(period["latest"], release_id).set_index("sector_name")
    then = _sector_totals(period["year_ago"], release_id).set_index(
        "sector_name")
    rows = []
    for sector in sorted(set(now.index) | set(then.index)):
        current = float(now["stage2_ead"].get(sector, 0.0))
        prior = float(then["stage2_ead"].get(sector, 0.0))
        rows.append({
            "sector_name": sector, "prior": prior, "current": current,
            "change": current - prior,
            "status": ("entered" if sector not in then.index else
                       "exited" if sector not in now.index else "present")})
    rows.sort(key=lambda r: (-r["change"], r["sector_name"]))
    return {"period": period["latest"], "comparison": period["year_ago"],
            "rows": rows, "row_count": len(rows),
            "sectors_in_either": len(rows),
            "total_change": sum(r["change"] for r in rows)}


def _growth(new: float, old: float) -> float | None:
    """A zero base has no growth RATE. Undefined is the honest answer."""
    return None if old == 0 else (new - old) / old


def _q07(release_id: str) -> dict[str, Any]:
    period = periods(release_id)
    now = _sector_totals(period["latest"], release_id).set_index("sector_name")
    then = _sector_totals(period["prior"], release_id).set_index("sector_name")
    rows, undefined = [], []
    for sector in sorted(set(now.index) & set(then.index)):
        ecl_growth = _growth(float(now["ecl"][sector]),
                             float(then["ecl"][sector]))
        ead_growth = _growth(float(now["ead"][sector]),
                             float(then["ead"][sector]))
        if ecl_growth is None or ead_growth is None:
            undefined.append(sector)
            continue
        if ecl_growth > ead_growth:
            rows.append({"sector_name": sector, "ecl_growth": ecl_growth,
                         "ead_growth": ead_growth,
                         "gap": ecl_growth - ead_growth})
    rows.sort(key=lambda r: (-r["gap"], r["sector_name"]))
    return {"period": period["latest"], "comparison": period["prior"],
            "rows": rows, "row_count": len(rows),
            "growth_undefined": undefined}


def _q08(release_id: str) -> dict[str, Any]:
    period = periods(release_id)
    now = _sector_totals(period["latest"], release_id).set_index("sector_name")
    then = _sector_totals(period["prior"], release_id).set_index("sector_name")
    rows = []
    for sector in sorted(set(now.index) | set(then.index)):
        current = float(now["ecl"].get(sector, 0.0))
        prior = float(then["ecl"].get(sector, 0.0))
        rows.append({"sector_name": sector, "prior": prior,
                     "current": current, "contribution": current - prior})
